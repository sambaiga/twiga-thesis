"""MLPGAM-FPQR Design Ablation.

Two-phase experiment that isolates each FPQR design choice while controlling
for backbone hyperparameters (Phase 1 Optuna HPO with plain MLPGAMConfig).

Fourteen experiment groups:
    proposal      -- proposal_type: softmax / horizon / kumaraswamy
    tau_embed     -- tau_embed_type: TimeEmb / LinearEmb / ConvEmb
    n_quantiles   -- grid granularity: 9 / 14 / 23 / 36 / 57 / 90, geometrically
                     spaced (ratio (90/9)**(1/5) ≈ 1.585), matching the sweep
                     used in experiment/chapter-5-fpqr/fpqr_experiment.py
    num_cosines   -- cosine embedding capacity: 0 (TauRoPE) / 16 / 32 / 64
    rope_type     -- TauRoPE variant (num_cosines=0): linear / tau_pos / factored / direct
    crossing      -- crossing_penalty: 0 (off), 1 / 3.16 / 10 / 31.6 / 100,
                     a half-decade log sweep anchored at the default (10)
    sort_output   -- differentiable sort: False / True / True+λ=0
    qvn_type      -- value network: relu / softplus / monotone / monotone_cal
    loss_fn       -- pinball / huber-pinball (kappa sweep) / winkler
    lambda_cal    -- CALCE weight for monotone_cal: 0.001 / 0.005 / 0.01 / 0.05 / 0.1
    prop_nq       -- 2-D cell {softmax,kumaraswamy} x {nq_9,nq_23,nq_57}, drawn
                     from the same geometric N sweep as n_quantiles
    stop_gradient -- 2x2 {softmax,kuma} x {sg_on,sg_off}
    prop_loss     -- proposal training loss: wasserstein / sqda / sqda_kl / combined
    best_config   -- assembles winners from all groups

Datasets:
    MLVS-PT   -- real LV net-load, Madeira, Portugal (heavy-tailed, solar-driven)
    MLVS-UK   -- real LV net-load, Plymouth, UK (lighter-tailed)
    SYN-HT3   -- synthetic, Student-t(df=3) residuals, kurtosis≈84
    SYN-HT10  -- synthetic, Student-t(df=10) residuals, kurtosis≈0

    Synthetic datasets are generated by experiment/common/synthetic_netload.py.

Usage::

    python experiment/ch6_conformal/exploratory/mlpgamfpqr_ablation.py  # all groups, all datasets
    python experiment/ch6_conformal/exploratory/mlpgamfpqr_ablation.py --group proposal prop_loss
    python experiment/ch6_conformal/exploratory/mlpgamfpqr_ablation.py --dataset SYN-HT3 SYN-HT10
    python experiment/ch6_conformal/exploratory/mlpgamfpqr_ablation.py --skip-hpo
    python experiment/ch6_conformal/exploratory/mlpgamfpqr_ablation.py --epochs 10 --folds 3  # smoke test
"""

